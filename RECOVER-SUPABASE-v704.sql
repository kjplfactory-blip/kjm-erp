create or replace function public.reserve_erp_serials_v703(
  p_state_id text,
  p_kind text,
  p_count integer,
  p_device_id text,
  p_app_version text
)
returns table (start_serial bigint, end_serial bigint, reserved_count integer)
language plpgsql
security definer
set search_path = public
set lock_timeout = '8s'
set statement_timeout = '15s'
as $$
declare
  v_start bigint;
  v_count integer := greatest(1, least(coalesce(p_count, 1), 1000));
begin
  if p_state_id <> 'khushali-jewells-main' then raise exception 'Invalid ERP state identifier'; end if;
  if p_kind not in ('job', 'production', 'lot', 'bill') then raise exception 'Invalid ERP serial kind'; end if;
  if public.erp_app_build_v703(p_app_version) < 703 then raise exception 'ERP v703 or newer is required'; end if;

  insert into public.erp_serial_counters (state_id, serial_kind, next_value, app_version)
  values (p_state_id, p_kind, case when p_kind in ('job', 'production') then 1001 else 1 end, p_app_version)
  on conflict (state_id, serial_kind) do nothing;

  select next_value into v_start
  from public.erp_serial_counters
  where state_id = p_state_id and serial_kind = p_kind
  for update;

  update public.erp_serial_counters
  set next_value = v_start + v_count,
      updated_at = clock_timestamp(),
      last_device_id = nullif(p_device_id, ''),
      app_version = p_app_version
  where state_id = p_state_id and serial_kind = p_kind;

  return query select v_start, v_start + v_count - 1, v_count;
end;
$$;

create or replace function public.apply_erp_entity_changes_v703(
  p_state_id text,
  p_expected_revision bigint,
  p_operation_id text,
  p_device_id text,
  p_user_name text,
  p_app_version text,
  p_changes jsonb,
  p_backup_key text default null
)
returns table (
  saved boolean,
  current_revision bigint,
  legacy_revision bigint,
  current_updated_at timestamptz,
  duplicate_operation boolean,
  signal_revision bigint
)
language plpgsql
security definer
set search_path = public
set lock_timeout = '8s'
set statement_timeout = '55s'
as $$
declare
  v_meta public.erp_entity_meta%rowtype;
  v_next_revision bigint;
  v_now timestamptz := clock_timestamp();
  v_change jsonb;
  v_collection text;
  v_record_id text;
  v_operation text;
  v_record_data jsonb;
  v_signal_revision bigint := 0;
  v_operation_id text := nullif(trim(coalesce(p_operation_id, '')), '');
begin
  if p_state_id <> 'khushali-jewells-main' then raise exception 'Invalid ERP state identifier'; end if;
  if v_operation_id is null then raise exception 'Operation ID is required'; end if;
  if public.erp_app_build_v703(p_app_version) < 703 then raise exception 'ERP v703 or newer is required'; end if;

  select * into v_meta from public.erp_entity_meta where state_id = p_state_id for update;
  if v_meta.state_id is null then
    return query select false, 0::bigint, 0::bigint, null::timestamptz, false, 0::bigint;
    return;
  end if;

  if exists (select 1 from public.erp_entity_operations where state_id = p_state_id and operation_id = v_operation_id) then
    select o.revision, o.legacy_revision, o.saved_at
    into v_next_revision, v_meta.legacy_revision, v_now
    from public.erp_entity_operations o
    where o.state_id = p_state_id and o.operation_id = v_operation_id;
    select coalesce(revision, 0) into v_signal_revision from public.erp_sync_signal where id = p_state_id;
    return query select true, v_next_revision, v_meta.legacy_revision, v_now, true, coalesce(v_signal_revision, 0);
    return;
  end if;

  if v_meta.revision <> coalesce(p_expected_revision, -1) then
    return query select false, v_meta.revision, v_meta.legacy_revision, v_meta.updated_at, false, 0::bigint;
    return;
  end if;

  if nullif(trim(coalesce(p_backup_key, '')), '') is not null then
    insert into public.erp_backup_requests (state_id, backup_key, app_version)
    values (p_state_id, p_backup_key, p_app_version)
    on conflict (state_id, backup_key) do nothing;

    if not exists (
      select 1 from public.erp_state_backups
      where state_id = p_state_id and backup_key = p_backup_key
    ) then
      insert into public.erp_state_backups
        (id, state_id, backup_key, backup_kind, source_version, target_version,
         source_updated_at, profile, data, created_at)
      values
        (md5(p_state_id || ':' || p_backup_key), p_state_id, p_backup_key,
         case when p_backup_key like 'version-%' then 'version-upgrade' else 'daily' end,
         coalesce(nullif(v_meta.app_version, ''), 'unknown'), p_app_version,
         v_meta.updated_at,
         jsonb_build_object('normalized', true, 'createdBy', coalesce(nullif(p_user_name, ''), 'ERP User')),
         public.build_erp_normalized_snapshot_v703(p_state_id), v_now)
      on conflict (state_id, backup_key) do nothing;
    end if;

    update public.erp_backup_requests
    set status = 'complete', completed_at = v_now, error_detail = null
    where state_id = p_state_id and backup_key = p_backup_key;
  end if;

  v_next_revision := v_meta.revision + 1;

  for v_change in select value from jsonb_array_elements(coalesce(p_changes -> 'arrays', '[]'::jsonb))
  loop
    v_collection := nullif(v_change ->> 'collection', '');
    v_record_id := nullif(v_change ->> 'recordId', '');
    v_operation := case when v_change ->> 'operation' = 'delete' then 'delete' else 'upsert' end;
    v_record_data := v_change -> 'data';
    if v_collection is null or v_record_id is null then continue; end if;

    insert into public.erp_entity_records
      (state_id, collection, record_id, data, deleted, revision, updated_at, operation_id)
    values
      (p_state_id, v_collection, v_record_id,
       case when v_operation = 'delete' then null else v_record_data end,
       v_operation = 'delete', v_next_revision, v_now, v_operation_id)
    on conflict (state_id, collection, record_id) do update
    set data = excluded.data, deleted = excluded.deleted, revision = excluded.revision,
        updated_at = excluded.updated_at, operation_id = excluded.operation_id;

    insert into public.erp_entity_changes
      (state_id, revision, collection, record_id, operation, data, updated_at,
       operation_id, device_id, user_name, app_version)
    values
      (p_state_id, v_next_revision, v_collection, v_record_id, v_operation,
       case when v_operation = 'delete' then null else v_record_data end,
       v_now, v_operation_id, nullif(p_device_id, ''), nullif(p_user_name, ''), p_app_version);
  end loop;

  for v_change in select value from jsonb_array_elements(coalesce(p_changes -> 'values', '[]'::jsonb))
  loop
    v_record_id := nullif(v_change ->> 'key', '');
    v_operation := case when v_change ->> 'operation' = 'delete' then 'delete' else 'upsert' end;
    v_record_data := v_change -> 'data';
    if v_record_id is null then continue; end if;

    insert into public.erp_entity_records
      (state_id, collection, record_id, data, deleted, revision, updated_at, operation_id)
    values
      (p_state_id, '@value', v_record_id,
       case when v_operation = 'delete' then null else v_record_data end,
       v_operation = 'delete', v_next_revision, v_now, v_operation_id)
    on conflict (state_id, collection, record_id) do update
    set data = excluded.data, deleted = excluded.deleted, revision = excluded.revision,
        updated_at = excluded.updated_at, operation_id = excluded.operation_id;

    insert into public.erp_entity_changes
      (state_id, revision, collection, record_id, operation, data, updated_at,
       operation_id, device_id, user_name, app_version)
    values
      (p_state_id, v_next_revision, '@value', v_record_id, v_operation,
       case when v_operation = 'delete' then null else v_record_data end,
       v_now, v_operation_id, nullif(p_device_id, ''), nullif(p_user_name, ''), p_app_version);
  end loop;

  update public.erp_entity_meta
  set revision = v_next_revision, updated_at = v_now, app_version = p_app_version
  where state_id = p_state_id;

  insert into public.erp_entity_operations
    (state_id, operation_id, revision, legacy_revision, saved_at, device_id, user_name, app_version)
  values
    (p_state_id, v_operation_id, v_next_revision, v_meta.legacy_revision, v_now,
     nullif(p_device_id, ''), nullif(p_user_name, ''), p_app_version);

  insert into public.erp_sync_signal
    (id, updated_at, app_version, revision, last_operation_id, last_device_id)
  values
    (p_state_id, v_now, p_app_version, 1, v_operation_id, nullif(p_device_id, ''))
  on conflict (id) do update
  set updated_at = excluded.updated_at,
      app_version = excluded.app_version,
      revision = public.erp_sync_signal.revision + 1,
      last_operation_id = excluded.last_operation_id,
      last_device_id = excluded.last_device_id
  returning revision into v_signal_revision;

  if mod(v_next_revision, 250) = 0 then
    delete from public.erp_entity_changes where state_id = p_state_id and updated_at < v_now - interval '180 days';
    delete from public.erp_entity_operations where state_id = p_state_id and saved_at < v_now - interval '180 days';
    update public.erp_entity_meta
    set minimum_revision = coalesce((select min(revision) from public.erp_entity_changes where state_id = p_state_id), v_next_revision)
    where state_id = p_state_id;
  end if;

  return query select true, v_next_revision, v_meta.legacy_revision, v_now, false, coalesce(v_signal_revision, 0);
end;
$$;

create or replace function public.verify_erp_factory_out_v703(p_state_id text, p_bill_ids jsonb)
returns table (all_verified boolean, verified_count integer, current_revision bigint, current_updated_at timestamptz)
language plpgsql
security definer
set search_path = public
set statement_timeout = '15s'
as $$
declare
  v_bill_id text;
  v_bill jsonb;
  v_requested integer := 0;
  v_verified integer := 0;
  v_ledger_count integer := 0;
  v_revision bigint := 0;
  v_updated_at timestamptz;
begin
  if p_state_id <> 'khushali-jewells-main' then raise exception 'Invalid ERP state identifier'; end if;
  for v_bill_id in select distinct value from jsonb_array_elements_text(coalesce(p_bill_ids, '[]'::jsonb))
  loop
    v_requested := v_requested + 1;
    select data into v_bill from public.erp_entity_records
    where state_id = p_state_id and collection = 'bills' and record_id = v_bill_id and deleted = false;
    if v_bill is null or nullif(v_bill ->> 'factoryOutPostedAt', '') is null then continue; end if;
    select count(*) into v_ledger_count
    from public.erp_entity_records
    where state_id = p_state_id and collection = 'factoryLedger' and deleted = false
      and coalesce(data ->> 'sourceType', '') = 'bill'
      and coalesce(data ->> 'sourceId', data ->> 'billId', '') = v_bill_id;
    if v_ledger_count = 1 then v_verified := v_verified + 1; end if;
  end loop;
  select revision, updated_at into v_revision, v_updated_at
  from public.erp_entity_meta where state_id = p_state_id;
  return query select (v_requested > 0 and v_requested = v_verified), v_verified, coalesce(v_revision, 0), v_updated_at;
end;
$$;

create or replace function public.create_erp_normalized_backup_v703(
  p_state_id text,
  p_backup_key text,
  p_backup_kind text,
  p_user_name text,
  p_app_version text
)
returns table (saved boolean, backup_key text, created_at timestamptz)
language plpgsql
security definer
set search_path = public
set statement_timeout = '120s'
as $$
declare
  v_snapshot jsonb;
  v_now timestamptz := clock_timestamp();
  v_key text := nullif(trim(coalesce(p_backup_key, '')), '');
begin
  if p_state_id <> 'khushali-jewells-main' then raise exception 'Invalid ERP state identifier'; end if;
  if v_key is null then raise exception 'Backup key is required'; end if;
  if public.erp_app_build_v703(p_app_version) < 703 then raise exception 'ERP v703 or newer is required'; end if;
  if exists (select 1 from public.erp_state_backups where state_id = p_state_id and backup_key = v_key) then
    return query select true, v_key, (select b.created_at from public.erp_state_backups b where b.state_id = p_state_id and b.backup_key = v_key limit 1);
    return;
  end if;
  v_snapshot := public.build_erp_normalized_snapshot_v703(p_state_id);
  insert into public.erp_state_backups
    (id, state_id, backup_key, backup_kind, source_version, target_version,
     source_updated_at, profile, data, created_at)
  values
    (md5(p_state_id || ':' || v_key), p_state_id, v_key,
     case when p_backup_kind in ('version-upgrade', 'daily', 'manual') then p_backup_kind else 'daily' end,
     p_app_version, p_app_version, v_now,
     jsonb_build_object('createdBy', coalesce(nullif(p_user_name, ''), 'ERP User'), 'normalized', true),
     v_snapshot, v_now)
  on conflict (state_id, backup_key) do nothing;
  update public.erp_backup_requests
  set status = 'complete', completed_at = v_now, error_detail = null
  where state_id = p_state_id and backup_key = v_key;
  return query select true, v_key, v_now;
exception when others then
  update public.erp_backup_requests
  set status = 'failed', error_detail = left(sqlerrm, 500)
  where state_id = p_state_id and backup_key = v_key;
  raise;
end;
$$;

