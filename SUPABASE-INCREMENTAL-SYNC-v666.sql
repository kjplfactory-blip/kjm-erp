-- KHUSHALI JEWELLS ERP v666 - INCREMENTAL MULTI-DEVICE SYNC
-- Run once in Supabase Dashboard > SQL Editor after SUPABASE-ADVANCED-SYNC-v640.sql.
-- Non-destructive: existing public.erp_state data is preserved and remains a compatibility copy.

create table if not exists public.erp_entity_meta (
  state_id text primary key,
  revision bigint not null default 0,
  legacy_revision bigint not null default 0,
  minimum_revision bigint not null default 0,
  updated_at timestamptz not null default clock_timestamp(),
  app_version text not null default 'unknown'
);

create table if not exists public.erp_entity_records (
  state_id text not null,
  collection text not null,
  record_id text not null,
  data jsonb,
  deleted boolean not null default false,
  revision bigint not null default 0,
  updated_at timestamptz not null default clock_timestamp(),
  operation_id text,
  primary key (state_id, collection, record_id)
);

create table if not exists public.erp_entity_changes (
  id bigint generated by default as identity primary key,
  state_id text not null,
  revision bigint not null,
  collection text not null,
  record_id text not null,
  operation text not null check (operation in ('upsert', 'delete')),
  data jsonb,
  updated_at timestamptz not null default clock_timestamp(),
  operation_id text,
  device_id text,
  user_name text,
  app_version text not null default 'unknown',
  unique (state_id, revision, collection, record_id)
);

create table if not exists public.erp_entity_operations (
  state_id text not null,
  operation_id text not null,
  revision bigint not null,
  legacy_revision bigint not null default 0,
  saved_at timestamptz not null default clock_timestamp(),
  device_id text,
  user_name text,
  app_version text not null default 'unknown',
  primary key (state_id, operation_id)
);

create index if not exists erp_entity_changes_state_revision_idx
on public.erp_entity_changes (state_id, revision, id);

create index if not exists erp_entity_records_state_collection_idx
on public.erp_entity_records (state_id, collection, deleted, updated_at desc);

alter table public.erp_entity_meta enable row level security;
alter table public.erp_entity_records enable row level security;
alter table public.erp_entity_changes enable row level security;
alter table public.erp_entity_operations enable row level security;

