-- Seed normalized records only if the installation has not already been seeded.
do $$
declare
  v_state_id text := 'khushali-jewells-main';
  v_data jsonb;
  v_updated_at timestamptz;
  v_pair record;
begin
  select data, updated_at into v_data, v_updated_at
  from public.erp_state where id = v_state_id;

  if v_data is null then
    raise exception 'ERP state % was not found. No migration was performed.', v_state_id;
  end if;

  insert into public.erp_entity_meta
    (state_id, revision, legacy_revision, minimum_revision, updated_at, app_version, legacy_source_updated_at)
  values
    (v_state_id, 1, 1, 1, v_updated_at, coalesce(v_data ->> 'appVersion', 'unknown'), v_updated_at)
  on conflict (state_id) do nothing;

  if not exists (select 1 from public.erp_entity_records where state_id = v_state_id) then
    for v_pair in select key, value from jsonb_each(v_data)
    loop
      if jsonb_typeof(v_pair.value) = 'array'
         and jsonb_array_length(v_pair.value) > 0
         and not exists (
           select 1 from jsonb_array_elements(v_pair.value) item(value)
           where jsonb_typeof(item.value) <> 'object'
              or nullif(item.value ->> 'id', '') is null
         ) then
        insert into public.erp_entity_records
          (state_id, collection, record_id, data, deleted, revision, updated_at, operation_id)
        select v_state_id, v_pair.key, item.value ->> 'id', item.value, false, 1,
          v_updated_at, 'v703-seed'
        from jsonb_array_elements(v_pair.value) item(value)
        on conflict (state_id, collection, record_id) do nothing;
      else
        insert into public.erp_entity_records
          (state_id, collection, record_id, data, deleted, revision, updated_at, operation_id)
        values
          (v_state_id, '@value', v_pair.key, v_pair.value, false, 1, v_updated_at, 'v703-seed')
        on conflict (state_id, collection, record_id) do nothing;
      end if;
    end loop;
  end if;
end;
$$;

create or replace function public.erp_app_build_v703(p_version text)
returns integer
language sql
immutable
as $$
  select coalesce(nullif(regexp_replace(coalesce(p_version, ''), '[^0-9]', '', 'g'), '')::integer, 0)
$$;

create or replace function public.build_erp_normalized_snapshot_v703(p_state_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
set statement_timeout = '120s'
as $$
declare
  v_snapshot jsonb := '{}'::jsonb;
  v_row record;
begin
  for v_row in
    select record_id, data
    from public.erp_entity_records
    where state_id = p_state_id and collection = '@value' and deleted = false
    order by record_id
  loop
    v_snapshot := jsonb_set(v_snapshot, array[v_row.record_id], coalesce(v_row.data, 'null'::jsonb), true);
  end loop;

  for v_row in
    select collection, jsonb_agg(data order by updated_at, record_id) as items
    from public.erp_entity_records
    where state_id = p_state_id and collection <> '@value' and deleted = false
    group by collection
    order by collection
  loop
    v_snapshot := jsonb_set(v_snapshot, array[v_row.collection], coalesce(v_row.items, '[]'::jsonb), true);
  end loop;
  return v_snapshot;
end;
$$;

-- A v703 browser can temporarily fall back to the compatibility row when its
-- local revision no longer matches. This repair copies that newer, verified row
-- back into normalized storage without deleting either cloud backup.
create or replace function public.reconcile_erp_normalized_from_legacy_v704(
  p_state_id text,
  p_expected_source_updated_at timestamptz,
  p_app_version text
)
returns table (
  repaired boolean,
  current_revision bigint,
  source_updated_at timestamptz,
  bill_count integer
)
language plpgsql
security definer
set search_path = public
set lock_timeout = '15s'
set statement_timeout = '240s'
as $$
declare
  v_data jsonb;
  v_source_updated_at timestamptz;
  v_meta public.erp_entity_meta%rowtype;
  v_pair record;
  v_next_revision bigint;
  v_now timestamptz := clock_timestamp();
  v_suffix text;
  v_normalized_backup_key text;
  v_legacy_backup_key text;
  v_bill_count integer := 0;
begin
  if p_state_id <> 'khushali-jewells-main' then raise exception 'Invalid ERP state identifier'; end if;
  if public.erp_app_build_v703(p_app_version) < 704 then raise exception 'ERP v704 or newer is required'; end if;

  select data, updated_at into v_data, v_source_updated_at
  from public.erp_state
  where id = p_state_id
  for share;

  if v_data is null then raise exception 'ERP compatibility state % was not found', p_state_id; end if;
  if p_expected_source_updated_at is null or v_source_updated_at <> p_expected_source_updated_at then
    raise exception 'ERP compatibility state changed while reconciliation was starting';
  end if;

  select * into v_meta
  from public.erp_entity_meta
  where state_id = p_state_id
  for update;

  if v_meta.state_id is null then raise exception 'ERP normalized metadata % was not found', p_state_id; end if;
  if v_meta.legacy_source_updated_at is not null
     and v_meta.legacy_source_updated_at >= v_source_updated_at then
    if jsonb_typeof(v_data -> 'bills') = 'array' then
      v_bill_count := jsonb_array_length(v_data -> 'bills');
    end if;
    return query select false, v_meta.revision, v_source_updated_at, v_bill_count;
    return;
  end if;

  v_suffix := substr(md5(p_state_id || ':' || v_source_updated_at::text), 1, 16);
  v_normalized_backup_key := 'v704-normalized-before-' || v_suffix;
  v_legacy_backup_key := 'v704-legacy-source-' || v_suffix;

  insert into public.erp_state_backups
    (id, state_id, backup_key, backup_kind, source_version, target_version,
     source_updated_at, profile, data, created_at)
  values
    (md5(p_state_id || ':' || v_normalized_backup_key), p_state_id,
     v_normalized_backup_key, 'manual', coalesce(v_meta.app_version, 'unknown'),
     p_app_version, v_meta.updated_at,
     jsonb_build_object('normalized', true, 'reason', 'before-v704-reconciliation'),
     public.build_erp_normalized_snapshot_v703(p_state_id), v_now)
  on conflict (state_id, backup_key) do nothing;

  insert into public.erp_state_backups
    (id, state_id, backup_key, backup_kind, source_version, target_version,
     source_updated_at, profile, data, created_at)
  values
    (md5(p_state_id || ':' || v_legacy_backup_key), p_state_id,
     v_legacy_backup_key, 'manual', coalesce(v_data ->> 'appVersion', 'unknown'),
     p_app_version, v_source_updated_at,
     jsonb_build_object('normalized', false, 'reason', 'v704-reconciliation-source'),
     v_data, v_now)
  on conflict (state_id, backup_key) do nothing;

  v_next_revision := greatest(coalesce(v_meta.revision, 0), coalesce(v_meta.legacy_revision, 0), 1) + 1;

  delete from public.erp_entity_changes where state_id = p_state_id;
  delete from public.erp_entity_operations where state_id = p_state_id;
  delete from public.erp_entity_records where state_id = p_state_id;

  for v_pair in select key, value from jsonb_each(v_data)
  loop
    if jsonb_typeof(v_pair.value) = 'array'
       and jsonb_array_length(v_pair.value) > 0
       and not exists (
         select 1 from jsonb_array_elements(v_pair.value) item(value)
         where jsonb_typeof(item.value) <> 'object'
            or nullif(item.value ->> 'id', '') is null
       ) then
      insert into public.erp_entity_records
        (state_id, collection, record_id, data, deleted, revision, updated_at, operation_id)
      select p_state_id, v_pair.key, item.value ->> 'id', item.value, false,
        v_next_revision, v_now, 'v704-legacy-reconcile'
      from jsonb_array_elements(v_pair.value) item(value)
      on conflict (state_id, collection, record_id) do nothing;
    else
      insert into public.erp_entity_records
        (state_id, collection, record_id, data, deleted, revision, updated_at, operation_id)
      values
        (p_state_id, '@value', v_pair.key, v_pair.value, false,
         v_next_revision, v_now, 'v704-legacy-reconcile');
    end if;
  end loop;

  update public.erp_entity_meta
  set revision = v_next_revision,
      legacy_revision = v_next_revision,
      minimum_revision = v_next_revision,
      updated_at = v_now,
      app_version = p_app_version,
      legacy_source_updated_at = v_source_updated_at
  where state_id = p_state_id;

  insert into public.erp_sync_signal
    (id, updated_at, app_version, revision, last_operation_id, last_device_id)
  values
    (p_state_id, v_now, p_app_version, 1, 'v704-legacy-reconcile', 'supabase-sql-recovery')
  on conflict (id) do update
  set updated_at = excluded.updated_at,
      app_version = excluded.app_version,
      revision = public.erp_sync_signal.revision + 1,
      last_operation_id = excluded.last_operation_id,
      last_device_id = excluded.last_device_id;

  if jsonb_typeof(v_data -> 'bills') = 'array' then
    v_bill_count := jsonb_array_length(v_data -> 'bills');
  end if;
  return query select true, v_next_revision, v_source_updated_at, v_bill_count;
end;
$$;

